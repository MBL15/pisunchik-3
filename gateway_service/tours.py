"""Интерактивные туры по интерфейсу: порядок шагов и тексты. Сам тур рисует `static/tour.js`.

Шаг — `{"sel": CSS-селектор, "title", "text"}` (+ `"closest"` — подсветить ближайшего предка). Если элемента нет на странице
(скрыт на узком экране, нет данных), шаг пропускается. Тур необязателен: он предлагается один раз и запускается
кнопкой «?» или клавишей «?» в любой момент.
"""
from shared import domain

HELP_STEP = {"sel": "[data-tour-start]", "title": "Тур всегда под рукой",
             "text": "Эта кнопка снова запустит подсказки по текущей странице. То же делает клавиша «?»."}


def _header(user: dict | None) -> list[dict]:
    steps = [{"sel": 'header nav[aria-label="Основная навигация"]', "title": "Главное меню",
              "text": "Календарь соревнований, рейтинг сезона, дисциплины и навигатор новичка — всё это доступно без входа."}]
    if not user:
        steps += [{"sel": 'header a[href="/register"]', "title": "Регистрация",
                   "text": "Создайте аккаунт за пару минут: выберите роли, укажите данные и сразу получите свой ФСП ID."},
                  {"sel": 'header a[href="/login"]', "title": "Вход",
                   "text": "Уже есть аккаунт? Войдите — откроется кабинет вашей роли."}]
        return steps
    if len(user["person"]["roles"]) > 1:
        steps.append({"sel": 'header form[aria-label^="Переключение роли"]', "title": "Переключатель ролей",
                      "text": "У вас несколько ролей. Нажмите нужную — кабинет и права сменятся сразу, входить заново не нужно."})
    steps += [{"sel": 'header a[href="/cabinet"]', "title": "Ваш кабинет",
               "text": "Сюда ведут все личные дела: заявки, результаты, документы и уведомления о сроках."},
              {"sel": 'header form[action="/logout"] button', "title": "Выход",
               "text": "Завершить сеанс. На общем компьютере выходите всегда."}]
    return steps


def _tour(tour_id: str, title: str, steps: list[dict], next_: tuple[str, str] | None = None) -> dict:
    return {"id": tour_id, "title": title, "steps": steps + [HELP_STEP],
            "next": {"href": next_[0], "label": next_[1]} if next_ else None}


