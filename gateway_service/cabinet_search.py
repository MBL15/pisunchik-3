def entries(role: str, telegram: bool = False) -> list[dict]:
    """Каталог функций активной роли: сначала её собственные, затем общие для всех. `telegram` — бот настроен."""
    own = list(_BY_ROLE.get(role, []))
    if telegram and role != Role.MINISTRY:
        own.append(_TELEGRAM)
    seen = {e[2] + e[0] for e in own}
    rows = own + [e for e in _COMMON if e[2] + e[0] not in seen]
    return [{"title": t, "hint": h, "href": href, "kw": kw, "where": where, "top": top}
            for t, h, href, kw, where, top in rows]
